type LanguageContextValue = {
  language: Language
  setLanguage: (language: Language) => void
  t: (text: string) => string
}

const LanguageContext = createContext<LanguageContextValue | null>(null)

export function LanguageProvider({
  initialLanguage,
  children,
}: {
  initialLanguage: Language
  children: React.ReactNode
}) {
  const [language, setLanguageState] = useState<Language>(initialLanguage)
  const t = useCallback((text: string) => (language === 'ta' ? tamil[text] ?? text : text), [language])

  useEffect(() => {
    document.documentElement.lang = language === 'ta' ? 'ta' : 'en'
  }, [language])

  const setLanguage = useCallback((nextLanguage: Language) => {
    setLanguageState(nextLanguage)
    document.cookie = `suvarna_language=${nextLanguage}; Path=/; Max-Age=31536000; SameSite=Lax`
  }, [])

  const value = useMemo(() => ({ language, setLanguage, t }), [language, setLanguage, t])

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function useLanguage() {
  const value = useContext(LanguageContext)
  if (!value) throw new Error('useLanguage must be used within LanguageProvider.')
  return value
}

export function LanguageSwitch() {
  const { language, setLanguage, t } = useLanguage()

  return (
    <div className="language-switch" role="group" aria-label={t('Choose language')}>
      <button type="button" aria-pressed={language === 'en'} onClick={() => setLanguage('en')}>
        English
      </button>
      <button type="button" aria-pressed={language === 'ta'} onClick={() => setLanguage('ta')}>
        தமிழ்
      </button>
    </div>
  )
}
